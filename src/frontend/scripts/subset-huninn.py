#!/usr/bin/env python3
"""
把 jf-openhuninn(粉圓)切成 unicode-range 子集,產生 src/fonts/huninn/*.woff2 與 src/app/huninn.css。

整顆字型 2.2MB,每個頁面都要等它下載完才會從系統字換成粉圓(display: swap),第一次開站常常好幾秒都
看起來像蘋方 / 微軟正黑。切塊後瀏覽器只下載頁面上真的出現的字所在的那幾塊:
  - ui:Latin、標點、全形符號,加上原始碼與語系檔裡出現過的每一個非 ASCII 字(介面文字幾乎都在這塊)。
  - cjk-NN:其餘中日韓漢字依碼位切成約 130KB 的區塊(使用者自己輸入的說明、檔名…才會用到)。
  - misc-NN:其餘符號、注音、假名、擴充區。
CSS 規範:同一個 family 的多個 @font-face,unicode-range 重疊時「後宣告的先試」,所以 ui 放在最後,
介面字一律由它提供;cjk 區塊的 range 用連續區間即可,不必把 ui 的字挖掉。

Splits jf-openhuninn into unicode-range subsets so a page downloads only the slices holding the
characters it shows, instead of the whole 2.2MB font before swapping away from the system font.
"ui" (Latin, punctuation, plus every non-ASCII character found in the source and locale files) is
declared last, so it wins wherever ranges overlap.

需求 / Needs: pip install fonttools brotli
用法 / Usage:  python3 scripts/subset-huninn.py      (run from src/frontend; re-run after adding UI text)
"""
from __future__ import annotations

import pathlib
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_FONT = ROOT / "src/fonts/jf-openhuninn-2.1.ttf"
OUT_DIR = ROOT / "src/fonts/huninn"
CSS_OUT = ROOT / "src/app/huninn.css"
FAMILY = "jf-openhuninn"

CJK_CHUNK = 750  # 每塊約 130KB / roughly 130KB per slice
MISC_CHUNK = 900

BASE_RANGES = [
    (0x0020, 0x007E),  # Basic Latin
    (0x00A0, 0x00FF),  # Latin-1
    (0x2000, 0x206F),  # General punctuation
    (0x2190, 0x21FF),  # Arrows
    (0x3000, 0x303F),  # CJK symbols & punctuation
    (0xFF00, 0xFFEF),  # Half/full-width forms
]


def is_cjk(cp: int) -> bool:
    return 0x4E00 <= cp <= 0x9FFF


def ui_codepoints() -> set[int]:
    """原始碼與語系檔裡出現的非 ASCII 字元。/ Non-ASCII characters used in the source and locales."""
    found: set[int] = set()
    for path in (ROOT / "src").rglob("*"):
        if path.suffix not in {".ts", ".tsx"} or "vendor" in path.parts:
            continue
        for ch in path.read_text(encoding="utf-8"):
            if ord(ch) > 0x7F:
                found.add(ord(ch))
    return found


def to_ranges(cps: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def css_range(ranges: list[tuple[int, int]]) -> str:
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def write_subset(name: str, cps: list[int]) -> int:
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.drop_tables += ["DSIG", "meta"]
    # recalcTimestamp=False:不把「現在時間」寫進 head 表,同樣的輸入產生同樣的位元組(git 不會白白變動)。
    # recalcTimestamp=False keeps the output byte-identical across runs (no "now" in the head table).
    font = TTFont(SRC_FONT, recalcTimestamp=False)
    sub = subset.Subsetter(options=opts)
    sub.populate(unicodes=cps)
    sub.subset(font)
    out = OUT_DIR / f"{name}.woff2"
    font.flavor = "woff2"
    font.save(out)
    return out.stat().st_size


def main() -> None:
    cmap = TTFont(SRC_FONT).getBestCmap()
    available = set(cmap)

    fixed = {cp for a, b in BASE_RANGES for cp in range(a, b + 1)} & available
    base = (fixed | ui_codepoints()) & available
    # cjk / misc 區塊只取決於字型本身(不扣掉 ui 的字),所以加了介面文字後重跑,只有 ui.woff2 與 CSS 會變,
    # 不會讓十幾個二進位檔全部改寫。重複的字由後宣告的 ui 區塊優先提供。
    # cjk / misc slices depend only on the font (UI characters are not carved out), so re-running after
    # adding UI text rewrites just ui.woff2 and the CSS instead of every binary; ui wins for duplicates.
    rest = sorted(available - fixed)
    cjk = [cp for cp in rest if is_cjk(cp)]
    misc = [cp for cp in rest if not is_cjk(cp)]

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for old in OUT_DIR.glob("*.woff2"):
        old.unlink()

    chunks: list[tuple[str, list[int], str]] = []
    for i in range(0, len(misc), MISC_CHUNK):
        part = misc[i:i + MISC_CHUNK]
        chunks.append((f"misc-{i // MISC_CHUNK:02d}", part, css_range(to_ranges(part))))
    for i in range(0, len(cjk), CJK_CHUNK):
        part = cjk[i:i + CJK_CHUNK]
        chunks.append((f"cjk-{i // CJK_CHUNK:02d}", part, f"U+{part[0]:X}-{part[-1]:X}"))
    chunks.append(("ui", sorted(base), css_range(to_ranges(sorted(base)))))

    lines = [
        "/* 由 scripts/subset-huninn.py 產生,請勿手改。/ Generated by scripts/subset-huninn.py — do not edit. */",
        "/* jf-openhuninn 2.1 (SIL OFL 1.1) — https://github.com/justfont/open-huninn-font */",
    ]
    total = 0
    for name, cps, urange in chunks:
        size = write_subset(name, cps)
        total += size
        print(f"{name:8s} {len(cps):5d} chars {size / 1024:7.1f} KB")
        lines.append(
            "@font-face {\n"
            f'  font-family: "{FAMILY}";\n'
            "  font-style: normal;\n"
            "  font-weight: 400;\n"
            "  font-display: swap;\n"
            f'  src: url("../fonts/huninn/{name}.woff2") format("woff2");\n'
            f"  unicode-range: {urange};\n"
            "}"
        )
    CSS_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"total    {sum(len(c[1]) for c in chunks):5d} chars {total / 1024:7.1f} KB -> {CSS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
